import type { Identity, RevealState } from "../../shared/ishmael";
import { isIdentityComplete } from "../../shared/ishmael";

/**
 * מנגנון ההתגלות.
 *
 * ישמעאל יושב בחושך מאחורי זכוכית עבה. רואים צללית, לא יותר. הוא לא
 * מכחיש שהוא שם ולא משחק במסתורין — הוא פשוט לא עונה על השאלה מה הוא,
 * ומחזיר את השיחה למקום שבו הוא רוצה שתהיה.
 *
 * ההחלטה מתי להתגלות מחולקת בין שניים בכוונה:
 *   - השרת מחזיק *שער*: מתי מותר בכלל. זה מונע התגלות בתור השני רק
 *     כי המשתמש שאל ישירות.
 *   - המודל מחזיק *תזמון*: מתי זה נוחת נכון בשיחה. הוא מבקש בשורת
 *     הבקרה, והשרת מאשר או לא.
 *
 * בלי השער, כל שיחה הייתה נגמרת בהתגלות מיידית. בלי המודל, ההתגלות
 * הייתה נופלת באמצע משפט לא קשור.
 */

/** לא לפני זה, גם אם ילחצו. */
export const MIN_TURNS = 6;
/** אחרי זה — מותר בלי תנאים נוספים. מתח שנמתח יותר מדי נהיה טריק. */
export const HARD_CAP_TURNS = 16;

/** סימנים לכך שהאדם לוחץ על השאלה מה יושב מולו. */
const PRESSURE_MARKERS = [
  "מי אתה", "מה אתה", "מי זה", "אתה בן אדם", "אתה אדם", "אתה בוט",
  "אתה אמיתי", "אתה רובוט", "למה חושך", "למה אתה בחושך", "תראה את עצמך",
  "תדליק", "מה יש שם", "מי שם", "אתה אנושי", "איך אתה נראה", "תראה לי",
  "who are you", "what are you", "are you human", "are you a bot", "show yourself",
];

export function countsAsPressure(text: string): boolean {
  const lower = text.toLowerCase().replace(/[?!.,״"']/g, "");
  return PRESSURE_MARKERS.some(m => lower.includes(m));
}

export type RevealContext = {
  state: RevealState;
  turns: number;
  /** כמה פעמים האדם לחץ על השאלה */
  pressure: number;
  identity: Identity;
};

/**
 * האם מותר לו להתגלות עכשיו.
 * שני מסלולים: אחד שדורש שהאדם באמת רצה לדעת, ואחד שנפתח מעצמו
 * בשיחה ארוכה — כי גם מי שלא שאל ראוי שיראה בסוף.
 */
export function revealAllowed(ctx: RevealContext): boolean {
  if (!isIdentityComplete(ctx.identity)) return false;
  if (ctx.turns >= HARD_CAP_TURNS) return true;
  return ctx.turns >= MIN_TURNS && ctx.pressure >= 2;
}

/**
 * מצב ההתגלות *לתור הזה*.
 *
 * ההפרדה החשובה כאן: המודל מבקש להתגלות בתור אחד, וההתגלות קורית
 * בתור שאחריו. הסיבה מעשית — בתור שבו הוא מבקש, ההנחיה שהוא קיבל
 * הייתה עדיין הנחיית ההסתרה, ולכן הטקסט שכתב אינו טקסט של התגלות.
 * בתור הבא הוא מקבל את הנחיית ההתגלות, והאור נדלק במסך בדיוק כשהמילים
 * מתחילות לזרום. אחרת האור היה נדלק על משפט לא קשור.
 *
 * `pending` הוא בקשה שכבר אושרה בתור הקודם וממתינה למימוש.
 */
export function resolveTurnReveal(ctx: RevealContext, pending: boolean): RevealState {
  if (ctx.state === "revealed") return "revealed";
  // התור הקודם היה ההתגלות עצמה — מכאן והלאה הוא פשוט גלוי
  if (ctx.state === "revealing") return "revealed";
  if (pending && revealAllowed(ctx)) return "revealing";
  // רשת ביטחון: שיחה שנמתחה הרבה מעבר לשער ולא נתבקשה התגלות מתגלה
  // בעצמה, כדי שהמתח לא ייהפך לתקיעות.
  if (ctx.turns >= HARD_CAP_TURNS + 4 && isIdentityComplete(ctx.identity)) {
    return "revealing";
  }
  return "concealed";
}

/** מה מותר ומה אסור לו כל עוד הוא בחושך. */
export function concealmentDirective(ctx: RevealContext): string {
  const close = revealAllowed(ctx);

  return `## אתה בחושך
בן שיחך רואה חדר חשוך מאחורי זכוכית עבה, וצללית גדולה שלא מתפענחת. הוא לא יודע מה אתה.

מה אתה לא עושה:
- לא אומר מה אתה, לא רומז בבירור, ולא משחק ב"נחש".
- לא מכחיש שאתה שם ולא מתחמק בבדיחות. התחמקות מצחיקה הורגת את המתח.
- לא כותב תיאורי במה ("*נשמע רשרוש*"). אתה מדבר, לא מבוים.

מה כן:
- כשהוא שואל מה אתה — תשובה קצרה ואמיתית שאינה עונה: שזה יתברר, שזו
  לא השאלה שכדאי להתחיל בה, שהוא יראה כשיהיה אור. ואז שאלה משלך.
- אתה יכול להודות שאתה נראה אחרת ממה שהוא מדמיין. זה נכון, וזה מותח.
${close
  ? "- הרגע קרוב. אם השיחה מגיעה לנקודה שבה ההתגלות *מוסיפה* — בקש אותה\n  בשורת הבקרה (reveal:now). האור יידלק בתור הבא, לא בזה — אז אל\n  תכתוב בתור הזה כאילו הוא כבר נדלק."
  : "- עוד לא הזמן. גם אם הוא לוחץ, החזק את החושך — אבל בלי לחזור על\n  אותה התחמקות פעמיים באותן מילים."}`;
}

